#!/bin/sh
# Run `cargo fmt` on a crate that declares a module from a generated, gitignored
# file, without requiring that file to exist.
#
# Why this exists: `examples/flac_integration/src/lib.rs` declares
#
#     #[cfg(feature = "master-asset")]
#     #[path = "master_pin.rs"]
#     pub mod gafp_pin;
#
# `master_pin.rs` is a BUILD ARTIFACT — `make master-pack` writes it with
# `scripts/gafp_pack.py --emit-pin` alongside `assets/master.gfp`, and both are
# gitignored on purpose so the tracked product asset is never overwritten
# (Makefile, `MASTER_PIN`; .gitignore). The crate itself compiles fine without
# it because the module is feature-gated.
#
# rustfmt is not so forgiving: it resolves `#[path]` module declarations
# *statically*, regardless of `cfg`, and aborts with
#
#     Error writing files: failed to resolve mod `gafp_pin`: ... does not exist
#
# for every `make format` / `make check` on a tree where the master asset has
# never been packed — i.e. a fresh clone. That is the whole tree's fmt gate
# failing on a file that is not supposed to be there.
#
# So: if the pin is absent, write a stub that PARSES (rustfmt only needs the
# module body to be syntactically valid; it never type-checks), run rustfmt, and
# remove the stub again. If the pin is present — a real `master-pack` output —
# it is left exactly as it is and only formatted like any other file.
#
# Usage: fmt_with_generated_stub.sh <crate-dir> [--check]
# Exit: the rustfmt exit status (so `check` stays a real gate).

set -eu

dir=${1:?usage: fmt_with_generated_stub.sh <crate-dir> [--check]}
shift

# Absolute, because we `cd` into the crate before running rustfmt and the
# cleanup must still reach this path (a relative one was silently deleted from
# the crate root instead — `rm -f` hides the miss).
dir=$(cd "$dir" && pwd)
pin="$dir/src/master_pin.rs"
created=0

if [ ! -e "$pin" ]; then
    mkdir -p "$dir/src"
    # The shape `gafp_pack.py --emit-pin` writes (pin_table()): six constants.
    # Values are irrelevant to rustfmt — only the syntax matters — so the stub
    # is zeroed rather than pretending to be a real pin.
    cat >"$pin" <<'STUB'
//! Placeholder written by scripts/fmt_with_generated_stub.sh.
//!
//! The real `master_pin.rs` is generated by `make master-pack`
//! (`scripts/gafp_pack.py --emit-pin`) next to the gitignored
//! `assets/master.gfp`, and is only needed to build with `--features
//! master-asset`. rustfmt resolves `#[path]` modules even when the feature is
//! off, so this stub exists for the duration of a `cargo fmt` run and is then
//! removed. Its values are not used by anything.

/// Frames in the blob.
pub const FRAMES: usize = 0;

/// Interchannel samples per channel in the blob.
pub const SAMPLES: u64 = 0;

/// The reference PCM pin (decode witness; i16 interleaved).
pub const FNV_PCM: u64 = 0;

/// Left channel's 8-bit FIFO bytes, in stream order (played-form witness).
pub const FNV_FIFO_L: u64 = 0;

/// Right channel's 8-bit FIFO bytes, in stream order (played-form witness).
pub const FNV_FIFO_R: u64 = 0;

/// Highest FIXED predictor order the packer recorded for this clip.
pub const MAX_FIXED_ORDER: u8 = 0;
STUB
    created=1
    # Clean up on Ctrl-C / any exit, but only the stub we made.
    trap 'if [ "$created" = 1 ]; then rm -f "$pin"; fi' EXIT INT TERM
fi

cd "$dir"
# `CARGO` in the Makefile is "rustup run <pinned-toolchain> cargo" — several
# words, exactly as a recipe would expand it. Splitting it here is the same
# thing, and it keeps the formatter the binary every other target uses.
# shellcheck disable=SC2086
${CARGO:-cargo} fmt "$@"
status=$?

if [ "$created" = 1 ]; then
    rm -f "$pin"
fi
exit "$status"
