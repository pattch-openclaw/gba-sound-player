#!/bin/sh
# Run `cargo fmt` on a crate that declares a module from a generated, gitignored
# file, without requiring that file to exist.
#
# Why this exists: `examples/flac_integration/src/lib.rs` declares
#
#     #[cfg(feature = "master-asset")]
#     #[path = "master_pin.rs"]
#     pub mod gafp_pin;
#
# `master_pin.rs` is a BUILD ARTIFACT — `make master-pack` writes it with
# `scripts/gafp_pack.py --emit-pin` alongside `assets/master.gfp`, and both are
# gitignored on purpose so the tracked product asset is never overwritten
# (Makefile, `MASTER_PIN`; .gitignore). The crate itself compiles fine without
# it because the module is feature-gated.
#
# rustfmt is not so forgiving: it resolves `#[path]` module declarations
# *statically*, regardless of `cfg`, and aborts with
#
#     Error writing files: failed to resolve mod `gafp_pin`: ... does not exist
#
# for every `make format` / `make check` on a tree where the master asset has
# never been packed — i.e. a fresh clone. That is the whole tree's fmt gate
# failing on a file that is not supposed to be there.
#
# So: if the pin is absent, write a stub that PARSES (rustfmt only needs the
# module body to be syntactically valid; it never type-checks), run rustfmt, and
# remove the stub again. If the pin is present — a real `master-pack` output —
# it is left exactly as it is and only formatted like any other file.
#
# The cwd is never changed. `cargo fmt --manifest-path` resolves `#[path]
# modules against the manifest's crate root, so this needs no `cd` — and that
# matters: an earlier version `cd`-ed into the crate and then removed a
# RELATIVE stub path, which silently deleted the wrong location (`rm -f` hides
# the miss) and left the stub behind. With no `cd`, every path in this script
# means the same thing from top to bottom.
#
# Usage: fmt_with_generated_stub.sh <crate-dir> [--check]
#        GENERATED=<absolute file> fmt_with_generated_stub.sh <crate-dir> [--check]
# Exit: the rustfmt exit status (so `check` stays a real gate).
#
# GENERATED names a generated module whose absence rustfmt cannot tolerate, when
# that module is not the master pin: examples/album_player declares
# `pub mod assets;` from a bake-generated `src/assets.rs`, and from 2a also
# `pub mod layout;` from a bake-generated `src/layout.rs`, and a fresh clone has
# neither. The stub it writes is comment-only, which is valid Rust for a whole
# module — rustfmt only needs the file to parse, never to type-check. With no
# GENERATED the script behaves exactly as before (the six-constant master-pin
# stub), so flac_integration's gate is byte-for-byte unchanged.
#
# GENERATED may hold SEVERAL such paths, colon-separated, because one crate can
# carry more than one generated module. Each absent one gets its own stub and
# each stub is removed by name; a generated file that already exists (a real
# `album-bake` output) is formatted in place and never touched, so the list never
# destroys the thing it is guarding.
#
# GENERATED is passed absolute (`$(abspath ...)` in the Makefile): the script
# never changes the cwd, so a relative path would work here, but an absolute one
# makes the stub that is created and the `rm -f` that removes it the same name no
# matter who calls the script from where — the failure this avoids (an earlier
# version removed a relative stub from the wrong directory) is silent.

set -eu

dir=${1:?usage: fmt_with_generated_stub.sh <crate-dir> [--check]}
shift

generated=${GENERATED:-}
if [ -n "$generated" ]; then
    # Colon-separated: one crate may own more than one generated module
    # (album_player's assets.rs and, from 2a, layout.rs).
    pins=$(printf '%s\n' "$generated" | tr ':' ' ')
else
    pins="$dir/src/master_pin.rs"
fi
created=""

for pin in $pins; do
    if [ -e "$pin" ]; then
        continue
    fi
    mkdir -p "$(dirname "$pin")"
    if [ -n "$generated" ]; then
        # A whole generated module, not one pin: an empty-module stub (comments
        # only) is what rustfmt needs, and it must not pretend to hold the
        # constants the crate reads — the real file is `make album-bake`'s.
        cat >"$pin" <<'STUB'
//! Placeholder written by scripts/fmt_with_generated_stub.sh.
//!
//! The real module is generated by `make album-bake` and is a build artifact
//! (ALBUM-PLAYER.md §2.3, §9.0). rustfmt resolves a crate's `mod` declarations
//! statically, so this comment-only stub exists for the duration of a
//! `cargo fmt` run and is then removed. No item here is real.
STUB
    else
        # The shape `gafp_pack.py --emit-pin` writes (pin_table()): six constants.
        # Values are irrelevant to rustfmt — only the syntax matters — so the stub
        # is zeroed rather than pretending to be a real pin.
        cat >"$pin" <<'STUB'
//! Placeholder written by scripts/fmt_with_generated_stub.sh.
//!
//! The real `master_pin.rs` is generated by `make master-pack`
//! (`scripts/gafp_pack.py --emit-pin`) next to the gitignored
//! `assets/master.gfp`, and is only needed to build with `--features
//! master-asset`. rustfmt resolves `#[path]` modules even when the feature is
//! off, so this stub exists for the duration of a `cargo fmt` run and is then
//! removed. Its values are not used by anything.

/// Frames in the blob.
pub const FRAMES: usize = 0;

/// Interchannel samples per channel in the blob.
pub const SAMPLES: u64 = 0;

/// The reference PCM pin (decode witness; i16 interleaved).
pub const FNV_PCM: u64 = 0;

/// Left channel's 8-bit FIFO bytes, in stream order (played-form witness).
pub const FNV_FIFO_L: u64 = 0;

/// Right channel's 8-bit FIFO bytes, in stream order (played-form witness).
pub const FNV_FIFO_R: u64 = 0;

/// Highest FIXED predictor order the packer recorded for this clip.
pub const MAX_FIXED_ORDER: u8 = 0;
STUB
    fi
    created="$created $pin"
done

if [ -n "$created" ]; then
    # Clean up on Ctrl-C / any exit, but only the stubs this run made — by name,
    # so a real generated file that was already present is never removed.
    trap 'for stub in $created; do rm -f "$stub"; done' EXIT INT TERM
fi

# No `cd`: the working directory never has to change, so there is no window in
# which `$pin` (or anything else) means something different. `cargo fmt
# --manifest-path` resolves `#[path]` modules against the MANIFEST's crate root,
# not the cwd — verified from an unrelated directory — so this formats exactly
# what `cd <crate> && cargo fmt` did.
#
# `CARGO` in the Makefile is "rustup run <pinned-toolchain> cargo" — several
# words, exactly as a recipe would expand it. Splitting it here is the same
# thing, and it keeps the formatter the binary every other target uses.
# shellcheck disable=SC2086
${CARGO:-cargo} fmt --manifest-path "$dir/Cargo.toml" "$@"
status=$?

for stub in $created; do
    rm -f "$stub"
done
exit "$status"
