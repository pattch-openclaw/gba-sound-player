//! Committed golden vector table for the E10 `rice_unmap` fold kernel (PR A).
//!
//! `(folded input, expected unmapped i32)` pairs — the single ground truth shared
//! by the host witness tests (`make kernel-test`) and the kernel-check ROM sweep,
//! so the host twin and the assembly are judged against the SAME bytes (the
//! repo's shared-consumer rule — one transcription, never a second ROM-side copy
//! that could share a mistake).
//!
//! Generation recipe (deterministic — re-running it must reproduce this file
//! byte-for-byte, the regeneration-tripwire convention):
//!
//! - `random.seed(20261016)` (Python `random`)
//! - inputs in order:
//!   - dense `0..=255` (256 candidates)
//!   - dense `0xFFFFFF00..=0xFFFFFFFF` (256 candidates)
//!   - `[1 << k, (1 << k) - 1, (1 << k) + 1]` for every `k` in `0..32` (96 candidates)
//!   - 256 uniform `rand32` draws (256 candidates)
//! - a later input equal to an earlier one is skipped — 25 in the single-bit edges stage (96 candidates → 71) — leaving 839 vectors; the census
//!   below makes duplicate inputs impossible, so a regeneration that lands a
//!   different count is drift, not noise
//! - expected = the corrected §9.2.7.2 unmap **as a definition**: even → `n >> 1`,
//!   odd → `!(n >> 1)`, reinterpreted as `i32`. `tests/unmap_twin.rs` judges it
//!   four ways: the definition re-derived in Rust, the SWAR twin
//!   (`(n >> 1) ^ (-(n & 1))` — the assembly's shape), a negate-and-subtract
//!   oracle, and — the mechanism anchor — round-trip against the **encoder-side**
//!   fold from §9.2.7.2 (`x ≥ 0 → 2x`, `x < 0 → −2x − 1`): a sign-convention
//!   misreading cannot survive composing with the encoder's rule
//!
//! Fail-closed census enforced at generation time (re-asserted on the host by
//! `tests/unmap_twin.rs::vector_census`): 839 vectors, no duplicate inputs, both
//! input parities present, and the expected outcomes include the pins 0 (from 0),
//! −1 (from 1), `i32::MAX` (from 0xFFFFFFFE) and `i32::MIN` (from 0xFFFFFFFF —
//! the value §9.2.7.3 forbids in a stream: this total fold maps it, rejecting it
//! stays upstream in `decode_rice_partition`), plus the RFC worked example 38 → 19.

