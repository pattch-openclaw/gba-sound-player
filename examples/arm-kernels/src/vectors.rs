//! Committed golden vector table for the E10 C1 kernel (`ctz32`).
//!
//! `(input, expected)` pairs — the single ground truth shared by the host
//! witness tests (`make kernel-test`) and the kernel-check ROM sweep, so the
//! host twin and the assembly are judged against the SAME bytes. This is the
//! repo's shared-consumer rule: one transcription of the expectation, never
//! a second ROM-side copy that could share a mistake.
//!
//! Generation recipe (deterministic — re-running it must reproduce this file
//! byte-for-byte, the regeneration-tripwire convention):
//!
//! - `random.seed(20261014)` (Python `random`)
//! - inputs in order: `0` (the sentinel — answer 32, "run past the window");
//!   `[1 << b for b in 0..32]`; 4 per shift position `k in 0..32` of
//!   `(rand31 | 1) << k` (odd mantissa landing at every trailing position);
//!   192 uniform `rand32` draws; the fixed edges `0xFFFFFFFF, 0xFFFFFFFE,
//!   0x80000000, 0x00000001, 0x55555555, 0xAAAAAAAA, 0x7FFFFFFF, 0x0000FFFF,
//!   0xFFFF0000`
//! - a later input equal to an earlier one is skipped: 362 candidates, 16
//!   skips (14 in the odd-mantissa stage — an odd-mantissa draw landing on
//!   an earlier one; 0 in the uniform stage; 2 at the edges, where
//!   `0x00000001` and `0x80000000` coincide with single-bit vectors),
//!   leaving 346 — the census below makes duplicate inputs impossible, so
//!   a regeneration that lands a different count is drift, not noise
//! - expected = `ctz(w)`, with `32` for `w == 0`
//!
//! Fail-closed census enforced at generation time (re-asserted on the host
//! by `tests/host_twin.rs::vector_census`): 346 vectors, no duplicate
//! inputs, expected outcomes cover all 33 values (0..=31 plus the sentinel).

