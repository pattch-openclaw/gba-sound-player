#[test]
fn both_clocks_divide_the_tick_clock_exactly() {
    for row in clock_rows() {
        println!(
            "clock {:>6} Hz: {} ticks/sample, period {} cycles, 2048-sample frame {} cycles",
            row.rate_hz, row.ticks_per_sample, row.period_cycles, row.frame_cycles
        );
        assert_eq!(row.ticks_per_sample * row.rate_hz, geometry::MIXER_TICK_HZ);
        assert_eq!(row.frame_cycles, 2_048 * row.ticks_per_sample);
        let sustained_periods = row.frame_cycles as f64 / row.period_cycles as f64;
        assert!(
            sustained_periods > 1.0,
            "{} Hz: a frame is more than one period",
            row.rate_hz
        );
    }
    // The product clock is the shipped one: 1,024 ticks/sample, 573,440 cycles a
    // period (§geometry's own pins, restated here at the clock the ROM runs).
    let product = &clock_rows()[0];
    assert_eq!(product.rate_hz, geometry::PLAYBACK_RATE_HZ);
    assert_eq!(product.ticks_per_sample, geometry::TICKS_PER_SAMPLE);
    assert_eq!(product.period_cycles, geometry::PERIOD_CYCLES);
    assert_eq!(product.frame_cycles, geometry::frame_cycles(2_048));
}

