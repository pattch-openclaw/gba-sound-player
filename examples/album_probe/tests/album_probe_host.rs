#[test]
fn position_never_moves_backwards_within_a_track() {
    let mut clock = position::SessionClock::new();
    let mut last = 0;
    for step in 0..400u32 {
        if step % 37 != 0 {
            // Every 37th step is a stall: the producer missed a period.
            clock.commit_chunk();
        }
        let painted = clock.paint_position();
        assert!(painted >= last, "step {step}: {painted} < {last}");
        last = painted;
    }
}

#[test]
fn position_lands_on_the_track_length_at_the_end() {
    let n = synth::TRACK_SAMPLES[1];
    let mut clock = position::SessionClock::new();
    while clock.committed() < n + position::LEAD_SAMPLES {
        clock.commit_chunk();
    }
    assert!(
        clock.paint_position() >= n,
        "the end of the track is reached"
    );
    assert_eq!(
        clock.paint_position_in_track(n),
        n,
        "and clamps to n_samples"
    );
}

#[test]
fn position_resets_to_zero_at_a_skip_and_the_reprime_silence_does_not_show() {
    // §4.4's six steps, as the clock sees them: the drop resets the counter, the
    // silence chunks fed to keep the DMA alive are committed but must not read
    // as position, and the new track then advances monotonically from 0.
    let mut clock = position::SessionClock::new();
    clock.commit(position::LEAD_SAMPLES + 100);
    assert!(clock.paint_position() > 0);

    clock.restart(); // step 2/3: the queue is dropped, the track starts exact
    assert_eq!(clock.paint_position(), 0);

    const SKIP_PRIME_CHUNKS: u32 = 4; // §4.4's candidate, Stage B sweeps it
    for _ in 0..SKIP_PRIME_CHUNKS {
        clock.commit_chunk(); // step 4: silence keeps the DMA fed
        assert_eq!(
            clock.paint_position(),
            0,
            "re-prime silence is not position"
        );
    }

    let mut last = clock.paint_position();
    for _ in 0..32 {
        clock.commit_chunk(); // steps 5/6: re-prime, fade in, keep playing
        let painted = clock.paint_position();
        assert!(painted >= last);
        last = painted;
    }
    assert!(last > 0, "the new track's position advances");
}

#[test]
fn the_lead_is_a_ring_constant() {
    assert_eq!(
        position::LEAD_SAMPLES as usize,
        geometry::RING_SAMPLES - geometry::PREFILL_SAMPLES + geometry::CHUNK_SAMPLES
    );
    assert!(
        position::LEAD_SAMPLES as usize >= geometry::PREFILL_SAMPLES,
        "the lead covers the prefill, or a start would show a position"
    );
    assert!(
        position::LEAD_SAMPLES as usize >= 4 * geometry::CHUNK_SAMPLES + geometry::CHUNK_SAMPLES,
        "the lead covers a re-prime's silence plus the buffer in flight"
    );
}

// ---------------------------------------------------------------------------
// 5. geometry, at both clocks (§4.2b's rules)
// ---------------------------------------------------------------------------

/// One row of the derivation table: what a clock implies, from the included
/// geometry constants plus that clock's own shift.
struct ClockRow {
    rate_hz: u32,
    ticks_per_sample: u32,
    period_cycles: u32,
    frame_cycles: u32,
}

fn clock_rows() -> Vec<ClockRow> {
    // The tick clock is 2^24 (§geometry); dividing it by a clock that is a power
    // of two is a shift, and both rates in the album's budget are powers of two.
    [(16_384u32, 14u32), (32_768, 15)]
        .into_iter()
        .map(|(rate_hz, log2)| {
            assert_eq!(rate_hz, 1 << log2, "{rate_hz} Hz is 1 << {log2}");
            assert_eq!(geometry::MIXER_TICK_HZ % rate_hz, 0, "exact ticks");
            let ticks_per_sample = geometry::MIXER_TICK_HZ >> log2;
            ClockRow {
                rate_hz,
                ticks_per_sample,
                period_cycles: geometry::CHUNK_SAMPLES as u32 * ticks_per_sample,
                frame_cycles: 2_048 * ticks_per_sample,
            }
        })
        .collect()
}

