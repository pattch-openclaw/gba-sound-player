#[test]
fn palette_bank_is_rgb15_and_padded() {
    let art = parsed();
    let bank = art.palette_bank(0);
    assert_eq!(bank.len(), 16);
    for (index, entry) in bank.iter().enumerate() {
        assert_eq!(entry & 0x8000, 0, "entry {index} is Rgb15, bit 15 clear");
        if index < pin::PALETTE_COLOURS as usize {
            // Entry 0 is the card's darkest colour rather than "transparent":
            // this blob is a BG, and ART1.md makes entry 0 an ordinary entry.
            assert!(bank[index] != 0 || index == 0, "entry {index} is used");
        } else {
            assert_eq!(*entry, 0, "unused entry {index} is zero");
        }
    }
}

