//! The AP-0 host gate: the parts the probe ROMs measure, proved as arithmetic
//! before any of them runs.
//!
//! Seven claims, each with its own tests so a failure names one of them:
//!
//! 1. the committed `ART1` blob parses, and every field it declares agrees with
//!    `ART1.md` and with `src/art_pin.rs` (the tool that generated it);
//! 2. every refusal in `ART1.md`'s list fires, from a byte this suite mutated;
//! 3. §6's `mm:ss` is exact over the range it is claimed for, and the bar cell
//!    has the four bake-time properties — and `src/nodiv.rs` has exactly one
//!    divide in it, the tagged bake-time one;
//! 4. the session clock is 0 at a start, n at an end, and never backwards within
//!    a track (including across a pause and across a skip's re-prime);
//! 5. the geometry's §4.2b rules hold at **both** clocks (16,384 and 32,768 Hz),
//!    read through the `#[path]`-included geometry module rather than restated;
//! 6. the synthetic source is deterministic, in profile, and produces the track
//!    lengths its table declares;
//! 7. §4.4's drop costs one period per queued chunk on the real `RingFeed`, so the
//!    skip probe's `drop` arm measures a ceiling the code proves.
//!
//! This is a host test: `std`, no `agb`, and the library it links is the same one
//! the ROMs compile, so nothing here can be true of a model and false of the
//! image.

use album_probe::art1::{self, Art1, Refusal};
use album_probe::playback::{Chunk, RingFeed};
use album_probe::{art_pin as pin, geometry, nodiv, position, synth};

/// The committed blob, generated by `scripts/album_probe_art.py` — run
/// `make album-probe-art`. `include_bytes!` makes a missing file a compile
/// error naming this path, which is the loud failure this gate wants; there is
/// no runtime default and no skip.
const BLOB: &[u8] = include_bytes!("../assets/probe_art1.bin");

/// Byte offset of the map section, derived the same way the reader derives it.
const MAP_OFF: usize = art1::HEADER_BYTES
    + pin::N_PALETTE_BANKS as usize * art1::PALETTE_BANK_BYTES
    + pin::N_TILES as usize * art1::TILE_BYTES;

fn parsed() -> Art1<'static> {
    match art1::parse(BLOB) {
        Ok(art) => art,
        Err(refusal) => panic!("the committed ART1 blob was refused: {refusal}"),
    }
}

fn word(offset: usize) -> u32 {
    u32::from_le_bytes([
        BLOB[offset],
        BLOB[offset + 1],
        BLOB[offset + 2],
        BLOB[offset + 3],
    ])
}

/// Parse a copy of the committed blob with one byte (or length) mutated. The
/// committed slice itself is never touched.
fn refuse_after(edit: impl FnOnce(&mut Vec<u8>)) -> Refusal {
    let mut copy = BLOB.to_vec();
    edit(&mut copy);
    match art1::parse(&copy) {
        Ok(_) => panic!("a mutated blob was accepted"),
        Err(refusal) => refusal,
    }
}

