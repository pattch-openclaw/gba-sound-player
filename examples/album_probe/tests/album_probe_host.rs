/// The defect round 2 removed: `fill_frame` used to zero-fill past the track end,
/// and the UI sweep consumes ~91,000 samples against track 0's 65,520, so the
/// `obj` tail and the whole `full` arm measured themselves converting silence.
///
/// The source is continuous now — at the end of a track it rolls to the next one —
/// so this walks 200 chunks (112,000 samples: past one track and past the UI
/// sweep's whole budget) and refuses an all-zero frame anywhere in it.
#[test]
fn synth_never_runs_out_past_a_track_end() {
    let mut source = synth::Synth::new();
    let (mut left, mut right) = ([0i32; 560], [0i32; 560]);
    let mut seen_tracks = [false; synth::N_TRACKS];
    for chunk in 0..200 {
        assert_eq!(source.fill_frame(&mut left, &mut right), 560);
        assert!(
            left.iter().any(|&s| s != 0),
            "chunk {chunk} came back silent — the source ran out at track {}",
            source.track()
        );
        assert_eq!(left, right, "the synthetic source is mono in both channels");
        seen_tracks[source.track()] = true;
    }
    assert!(
        seen_tracks[0] && seen_tracks[1],
        "112,000 samples crossed track 0's 65,520 and rolled to track 1"
    );

    // The roll is a re-seek, not a different waveform: the 560 samples after the
    // seam are exactly what a fresh source seeked to track 1 produces.
    let mut rolled = synth::Synth::new();
    let len = synth::TRACK_SAMPLES[0] as usize;
    let (mut big_l, mut big_r) = (vec![0i32; len], vec![0i32; len]);
    rolled.fill_frame(&mut big_l, &mut big_r);
    assert!(
        rolled.finished() && rolled.track() == 0,
        "a whole track 0 has been produced and the seam is one sample away"
    );
    rolled.fill_frame(&mut left, &mut right);
    assert_eq!(rolled.track(), 1, "the next sample rolled to track 1");
    let mut fresh = synth::Synth::new();
    fresh.start_track(1);
    let (mut fresh_l, mut fresh_r) = ([0i32; 560], [0i32; 560]);
    fresh.fill_frame(&mut fresh_l, &mut fresh_r);
    assert_eq!(left, fresh_l, "a rolled track is a re-seek of the next one");
    assert_eq!(right, fresh_r);
}

#[test]
fn synth_seek_changes_the_track() {
    let mut source = synth::Synth::new();
    let (mut left, mut right) = ([0i32; 560], [0i32; 560]);
    source.fill_frame(&mut left, &mut right);
    let first = left;
    source.start_track(2);
    assert_eq!(source.track(), 2);
    assert_eq!(source.pos_in_track(), 0);
    let mut other = synth::Synth::new();
    other.start_track(2);
    other.fill_frame(&mut right, &mut left);
    source.fill_frame(&mut left, &mut right);
    assert_ne!(first, left, "track 2 is not track 0");
}

// ---------------------------------------------------------------------------
// 7. §4.4's skip on the real ring: what consume-and-discard costs
// ---------------------------------------------------------------------------

/// §4.4 step 2 says the queued chunks are "dropped, not played". Before
/// `RingFeed::truncate` landed (with the §2.2 lift, 2026-11-15) the only drop the
/// application had was *consume-and-discard*, which costs one hardware period per
/// queued chunk. This test pins that arithmetic to the real ring type — the same
/// one `FEED` instantiates — so the skip probe's `drop` arm is measuring a cost the
/// code proves, not one the record asserts. (`truncate` itself is witnessed in
/// `crates/gba-playback`'s own suite, `make playback-test`; the other half of this
/// file's ceiling arithmetic is the test below.)
///
/// The numbers the record reads from it: the ring holds all 36 chunks (`push_bytes`
/// refuses only what needs more than `free`), so a skip at the ring's ceiling
/// depth discards 36 chunks = 36 periods = 1,230 ms before the silence cover
/// begins. The probe's deep arm queues 35 and lets the fade-out push take the
/// 36th, which is the same 36-chunk stale window.
#[test]
fn discarding_a_full_ring_costs_one_period_per_queued_chunk() {
    const RING: usize = geometry::RING_SAMPLES;
    const CHUNK: usize = geometry::CHUNK_SAMPLES;
    let mut ring = RingFeed::<RING>::new();
    let zeros = vec![0u8; CHUNK];
    while ring.free_samples() >= CHUNK {
        ring.push_bytes(&zeros, &zeros)
            .expect("a whole chunk fits while free >= CHUNK");
    }
    assert_eq!(
        ring.ready(),
        RING,
        "the ring fills to every one of its chunks"
    );

    let stale_frontier = ring.pushed();
    let mut left = vec![0u8; CHUNK];
    let mut right = vec![0u8; CHUNK];
    let mut periods = 0usize;
    while ring.consumed() < stale_frontier {
        assert_eq!(
            ring.take_chunk(&mut left, &mut right, CHUNK, false),
            Chunk::Full,
            "every stale chunk is a whole chunk the DMA reads"
        );
        periods += 1;
        assert!(
            periods <= RING / CHUNK,
            "the drop took more periods than there are queued chunks"
        );
    }
    assert_eq!(periods, RING / CHUNK);
    assert_eq!(periods, geometry::RING_CHUNKS);
    assert_eq!(ring.ready(), 0, "the stale window empties the ring");
}

/// The other half of the same ceiling, as the record's deep rows read it: a skip
/// at the ring's ceiling depth cannot reach new-track audio before the whole
/// queue has been consumed (36 chunks) plus the silence cover that re-primes it
/// (`SKIP_PRIME_CHUNKS`). At 34.18 ms a period that is 38-52 periods = 1.30-1.78 s,
/// against §4.4's ≤ ~0.6 s = 17.6 periods.
#[test]
fn a_skip_at_the_shipped_depth_costs_the_queue_plus_the_cover() {
    let period_ms =
        f64::from(geometry::PERIOD_CYCLES) / (f64::from(geometry::MIXER_TICK_HZ) / 1000.0);
    assert!(
        (period_ms - 34.18).abs() < 0.01,
        "a period is {period_ms} ms at the product rate"
    );
    let stale_periods = geometry::RING_CHUNKS;
    for prime_chunks in [2usize, 4, 8, 16] {
        let to_new_periods = stale_periods + prime_chunks;
        let to_new_ms = to_new_periods as f64 * period_ms;
        assert!(
            to_new_ms > 600.0,
            "prime {prime_chunks}: {to_new_periods} periods = {to_new_ms:.0} ms is already \
             outside §4.4's ~0.6 s — the ring depth is the budget"
        );
        // Truncating the queue in one step leaves only the cover in front of the
        // new audio — the row the skip probe's `truncate` arm now measures on mGBA
        // rather than derives here (`RingFeed::truncate`, landed 2026-11-15).
        let truncated_ms = (prime_chunks + 1) as f64 * period_ms;
        assert!(
            truncated_ms <= 600.0,
            "prime {prime_chunks}: a truncate would read {truncated_ms:.0} ms, inside §4.4"
        );
    }
}
