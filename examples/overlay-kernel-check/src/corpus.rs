//! The committed subframe-body corpus, parsed, and the independent width walk
//! that turns one of its frames into the partitions a `RiceKernel` is handed.
//!
//! One transcription of the walk, shared by two consumers (the repo's
//! shared-consumer rule, `examples/arm-kernels/src/vectors.rs`):
//!
//! * `crates/flac-lite-gba/tests/arm_from_outside.rs` — the host differential
//!   of 6a-4, run through `cargo test` on the host triple; and
//! * `examples/overlay-kernel-check/src/main.rs` — the 6a-4 instrument ROM, run
//!   through `mgba-test-runner` on the device.
//!
//! Both consumers declare this file with `#[path]`, so a change to the walk
//! cannot land on one side only: the host witness and the device witness move
//! together or the build breaks. That matters more here than usual, because the
//! walk is not plumbing — it *is* the claim about where each partition's bit
//! stream starts, and a ROM whose walk had drifted would be feeding a kernel a
//! partition that no real stream contains while still printing a clean result.
//!
//! The walk deliberately does not use either kernel's arithmetic: the unary
//! lengths are counted one bit at a time through a second `BitReader`, and the
//! partition chain is advanced off that walk's own end position, then checked
//! against the table's own `exit_bits` (which was generated by an independent
//! Python `Bits` walk, `scripts/frame_vectors.py`).
//!
//! Written against `alloc`, not `std`, so the ROM can compile it; the host test
//! gets the same code from a std binary.
#![allow(clippy::too_many_lines)] // a parser and a walk, in one file on purpose

extern crate alloc;

use alloc::string::{String, ToString};
use alloc::vec::Vec;
use flac_lite::bits::BitReader;
use flac_lite::frame::{FrameHeader, StreamDefaults};
use flac_lite::residual::PartitionHeader;
use flac_lite::subframe::{PredictorState, SubframeType};

/// The committed corpus, as bytes. `include_str!` resolves relative to *this
/// file*, which lives at one fixed place in the tree for both consumers, so the
/// path is stable where `env!("CARGO_MANIFEST_DIR")` would not be: the two
/// consumers are different crates with different manifest dirs. Each consumer
/// still embeds its own copy (this is compiled into each crate separately), so
/// the bytes never become a shared static — which is the property
/// `twin_from_outside.rs` established for the same data file.
const VECTOR_TABLE: &str =
    include_str!("../../../crates/flac-lite/tests/subframe_body_vectors.txt");

/// One vector of the committed corpus. Fields are `pub` because the two
/// consumers are different crates that each `#[path]`-include this source: a
/// field is the only way to hand it across, and every consumer reads the same
/// parsed value rather than re-parsing the table its own way.
pub struct Vector {
    pub label: String,
    pub frame: Vec<u8>,
    pub sample_rate_hz: u32,
    pub bits_per_sample: u8,
    pub blocksize: u64,
    pub kind: String,
    pub order: u64,
    pub exit_bits: u64,
}

pub fn load_corpus() -> Vec<Vector> {
    let mut out: Vec<Vector> = Vec::new();
    for line in VECTOR_TABLE.lines() {
        let line = line.trim();
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        let (key, value) = line.split_once(char::is_whitespace).unwrap_or((line, ""));
        let value = value.trim();
        if key == "body_vector" {
            out.push(Vector {
                label: value.to_string(),
                frame: Vec::new(),
                sample_rate_hz: 0,
                bits_per_sample: 0,
                blocksize: 0,
                kind: String::new(),
                order: 0,
                exit_bits: 0,
            });
            continue;
        }
        let v = out
            .last_mut()
            .unwrap_or_else(|| panic!("{key:?} outside a body_vector block"));
        let number = || {
            value
                .strip_prefix("0x")
                .and_then(|h| u64::from_str_radix(h, 16).ok())
                .or_else(|| {
                    value
                        .parse::<i64>()
                        .ok()
                        .and_then(|x| u64::try_from(x).ok())
                })
                .unwrap_or_else(|| panic!("{key:?} is not a number: {value:?}"))
        };
        match key {
            "frame_hex" => {
                v.frame = value
                    .split_whitespace()
                    .map(|b| {
                        u8::from_str_radix(b, 16).unwrap_or_else(|e| panic!("byte {b:?}: {e}"))
                    })
                    .collect();
            }
            "stream_samplerate_hz" => v.sample_rate_hz = number() as u32,
            "stream_bits_per_sample" => v.bits_per_sample = number() as u8,
            "blocksize" => v.blocksize = number(),
            "subframe_kind" => v.kind = value.to_string(),
            "subframe_order" => v.order = number(),
            "exit_bits" => v.exit_bits = number(),
            _ => {}
        }
    }
    assert!(!out.is_empty(), "the corpus table read as empty");
    out
}

/// One partition as the corpus walk sees it: the header, where its codewords
/// start, and the unary lengths a naive independent walk counted.
pub struct Part {
    pub header: PartitionHeader,
    pub body_at: usize,
    pub quotients: Vec<u32>,
}

/// Stand on the subframe's residual with the production parse's own sequence
/// (frame header → subframe type → wasted run → warm-up → LPC parameters), then
/// walk the partitions. The walk is the independent one: unary counted bit by bit,
/// bodies ended where the terminator is, so `body_at` never depends on either
/// kernel's arithmetic.
pub fn corpus_partitions(v: &Vector) -> Vec<Part> {
    let defaults = StreamDefaults {
        sample_rate_hz: v.sample_rate_hz,
        bits_per_sample: v.bits_per_sample,
    };
    let mut reader = BitReader::new(&v.frame);
    let header = FrameHeader::parse(&mut reader, &defaults)
        .unwrap_or_else(|e| panic!("{}: frame header: {e:?}", v.label));
    let kind = SubframeType::parse(&mut reader)
        .unwrap_or_else(|e| panic!("{}: subframe type: {e:?}", v.label));
    let order = kind.order();
    let wasted = reader
        .read_wasted_bits()
        .unwrap_or_else(|e| panic!("{}: wasted run: {e:?}", v.label));
    let bits = u8::try_from(header.bits_per_sample as u64 - u64::from(wasted))
        .expect("a subframe sample width that fits a u8");
    let mut state = PredictorState::new();
    state
        .fill(&mut reader, order, bits, 0)
        .unwrap_or_else(|e| panic!("{}: warm-up: {e:?}", v.label));
    if let SubframeType::Lpc { order } = kind {
        let precision = reader.read_bits(4).expect("LPC precision") + 1;
        reader.read_signed(5).expect("LPC shift");
        for c in 0..order {
            reader
                .read_signed(precision)
                .unwrap_or_else(|e| panic!("{}: LPC coefficient {c}: {e:?}", v.label));
        }
    }

    let method = reader.read_bits(2).expect("coding method");
    assert!(
        method <= 0b01,
        "{}: a partition method this reader refuses to walk: {method:#04b}",
        v.label
    );
    let param_bits = if method == 0b00 { 4 } else { 5 };
    let partition_order = reader.read_bits(4).expect("partition order") as usize;
    let per_partition =
        usize::try_from(v.blocksize >> partition_order).expect("per-partition count");
    let total = header.blocksize;
    let predictor_order = usize::try_from(order).expect("predictor order");

    let mut parts = Vec::new();
    for pnum in 0..(1usize << partition_order) {
        let field = reader.read_bits(param_bits).expect("partition parameter");
        let escaped = field == (1u32 << param_bits) - 1;
        let count = per_partition - if pnum == 0 { predictor_order } else { 0 };
        let mut ph = PartitionHeader {
            order: 0,
            is_escape: escaped,
            raw_bits: 0,
            sample_count: u16::try_from(count).expect("sample count"),
        };
        if escaped {
            ph.raw_bits = reader.read_bits(5).expect("escape width") as u8;
            let body_at = reader.bit_position();
            parts.push(Part {
                header: ph,
                body_at,
                quotients: Vec::new(),
            });
            // Chain: the escaped body is count x raw_bits wide, counted here
            // rather than trusted from either decoder.
            let body_end = body_at + count * usize::from(ph.raw_bits);
            let here = reader.bit_position();
            skip(&mut reader, body_end - here);
            continue;
        }
        ph.order = field as u8;
        let body_at = reader.bit_position();
        // An independent count of the unary lengths, walking bits rather than
        // trusting either decoder's run tiers.
        let mut probe = BitReader::new(&v.frame);
        skip(&mut probe, body_at);
        let mut quotients = Vec::with_capacity(count);
        for _ in 0..count {
            let mut q = 0u32;
            while probe.read_bits(1).expect("unary bit") == 0 {
                q += 1;
            }
            if ph.order > 0 {
                probe.read_bits(u32::from(ph.order)).expect("remainder");
            }
            quotients.push(q);
        }
        parts.push(Part {
            header: ph,
            body_at,
            quotients,
        });
        // Chain again, off the probe's own end, so the next partition's
        // parameter field is read from where this body actually stopped rather
        // than from an estimate. If the estimate were the thing under test, this
        // is where a desync would show up: the loop would start reading a
        // parameter out of the middle of a codeword and land somewhere with no
        // remainder bits left, which is exactly what this walk did when it was
        // left unchained.
        let here = reader.bit_position();
        skip(&mut reader, probe.bit_position() - here);
    }
    // The independent walk has to land on the table's own body end, which is the
    // same check `twin_from_outside.rs` makes of its walk. Re-derived here rather
    // than relied on, because this file's packer-side claims all hang off the
    // partition offsets this loop produces.
    assert_eq!(
        reader.bit_position(),
        usize::try_from(v.exit_bits).expect("exit_bits in a frame this size"),
        "{}: the width walk did not land on its own table's exit_bits",
        v.label
    );
    let _ = total;
    parts
}

/// Advance by `bits`: `read_bits` serves at most 32 at a time.
pub fn skip(reader: &mut BitReader<'_>, mut bits: usize) {
    while bits >= 32 {
        reader.read_bits(32).expect("seek a word");
        bits -= 32;
    }
    if bits > 0 {
        reader.read_bits(bits as u32).expect("seek the tail");
    }
}
