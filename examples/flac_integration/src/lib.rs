//! # flac_integration — the product crate's shared library
//!
//! The layer both of this crate's consumers compile against: the ROM that plays
//! (`src/product_play_main.rs`, `make native-product-play-rom`) and the host
//! model that decides ahead of time whether that ROM can be gapless
//! (`tests/product_play_witness.rs`, `make product-play-test`). It exists so the
//! two cannot disagree about the geometry, the ring protocol, or the reference
//! pins — the failure mode item 6b-3 was written to avoid: the plan records that
//! the throwaway rate-play harness in `examples/flac_spike` turned out to be
//! load-bearing in undocumented ways, so its measurement instrument is being
//! rebuilt on the product path rather than copied beside it.
//!
//! ```text
//!   geometry ──┬── the ROM (what the hardware actually did)
//!   gafp_pin   │
//!   playback   ┴── the host model (what the geometry implies, arithmetic)
//!   checksum
//! ```
//!
//! ## What is shared, and where it came from
//!
//! | module | provenance |
//! |---|---|
//! | [`geometry`] | this crate, item 6b-3. Every constant transcribed from `agb` 0.25.0, the GBA's own clock, or `scripts/gafp_pack.py`, with the source at the constant. |
//! | [`gafp_pin`] | generated by `scripts/gen_gafp_blob.py` from the perf gate's committed pins; describes the embedded `assets/spike_l0.gfp`. |
//! | [`playback`], [`checksum`] | `#[path]` includes of `examples/flac_spike/src/{playback,checksum}.rs` — one implementation, two consumers, no drift. Same pattern as `crates/flac-lite-gba/tests/arm_from_outside.rs`, which shares example sources for the same reason (one case set must not fork between consumers). The risk this carries is stated in `examples/flac_spike/src/playback.rs`'s own module docs: changing that file changes this crate's images too, and both crates' gates are the witness that it didn't. |
//!
//! Nothing here is platform-bound: no `agb`, no registers, no unsafe (hence
//! `#![forbid(unsafe_code)]`). The `agb`-facing half of the product path lives in
//! the ROM bins, which are arm-only (see each file's `cfg_attr`). This is the
//! separation `crates/flac-lite/README.md` states for the decoder itself — the
//! product's platform-bound parts stay out of anything the host can compile.

#![no_std]
#![forbid(unsafe_code)]

#[cfg(feature = "master-asset")]
#[path = "master_pin.rs"]
pub mod gafp_pin;
#[cfg(not(feature = "master-asset"))]
pub mod gafp_pin;
pub mod geometry;

// The shared pair. `playback.rs` reaches its checksum as `crate::checksum`, so
// the two are included together — that is the arrangement the spike crate has
// them in, and re-declaring one without the other is a compile error rather than
// a silent fork.
#[path = "../../flac_spike/src/checksum.rs"]
pub mod checksum;

/// The decode-to-FIFO path: truncation rule, ring accounting, underflow
/// classification. Host-testable, and the exact code the ROM runs — see the
/// module's own concurrency contract before changing how the producer and the
/// feeder share it.
//
// `allow(unexpected_cfgs)`: `playback.rs`'s unit-test suite rides a feature
// (`rate-assets`) that belongs to the crate the file *comes from*, not to this
// one. The predicate is false here on purpose — that suite was `make rate-test`'s (retired 2026-11-14)
// to run, and moving it would change the counts that gate reports (the
// coexistence contract in the Makefile). The attribute is here so cargo's
// unexpected-cfg lint doesn't call a deliberate boundary a mistake.
#[allow(unexpected_cfgs)]
#[path = "../../flac_spike/src/playback.rs"]
pub mod playback;
