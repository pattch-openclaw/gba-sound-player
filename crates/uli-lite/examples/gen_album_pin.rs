//! Generate a ULA2 album pin module from the bit-exact Rust decoder.
//!
//! This replaces the C-decoder-sourced `scripts/uli_album_pin.py` in the asset
//! path. The pin is the FNV-1a 32 of the little-endian per-frame int8 hashes,
//! in frame order, over every frame the album declares (including frame 0's
//! preroll), which is the same fold `examples/uli_bench` performs.
//!
//! The decoder used here is `uli_lite`, the checked portable reference and the
//! oracle the product `GbaDecoder` is twinned against. A pin generated from it
//! is therefore a reference-vs-product witness, not an independent C decode;
//! the optional `make uli-accept` oracle remains the byte-exactness instrument.
//!
//! Usage:
//!   cargo run --manifest-path crates/uli-lite/Cargo.toml \
//!     --target <host-triple> --release --example gen_album_pin -- \
//!     <album.uli> <out.rs>

use std::env;
use std::fs::{self, File};
use std::io::{BufWriter, Write};
use std::process;

use uli_lite::{Album, Decoder, DecoderState};

const M: usize = 512;

fn fnv_bytes(mut h: u32, bytes: &[u8]) -> u32 {
    for &b in bytes {
        h ^= b as u32;
        h = h.wrapping_mul(16_777_619);
    }
    h
}

fn fnv_i8(mut h: u32, l: &[i8], r: &[i8]) -> u32 {
    for &v in l {
        h ^= v as u8 as u32;
        h = h.wrapping_mul(16_777_619);
    }
    for &v in r {
        h ^= v as u8 as u32;
        h = h.wrapping_mul(16_777_619);
    }
    h
}

fn usage() -> String {
    "usage: gen_album_pin <album.uli> <out.rs>".to_string()
}

fn main() {
    if let Err(e) = run() {
        eprintln!("gen_album_pin: {e}");
        eprintln!("{}", usage());
        process::exit(1);
    }
}

fn run() -> Result<(), String> {
    let mut args = env::args().skip(1);
    let album_path = args.next().ok_or_else(usage)?;
    let out_path = args.next().ok_or_else(usage)?;
    if args.next().is_some() {
        return Err("too many arguments".to_string());
    }

    let blob = fs::read(&album_path).map_err(|e| format!("read {album_path}: {e}"))?;
    let album = Album::parse(&blob).map_err(|e| format!("album parse: {e:?}"))?;
    let mut state = Box::new(DecoderState::new());
    let mut decoder = Decoder::new(album, &mut state).map_err(|e| format!("tables: {e:?}"))?;

    let mut l8 = [0i8; M];
    let mut r8 = [0i8; M];
    let mut all8 = 2_166_136_261u32;

    for frame in 0..album.n_frames() {
        decoder
            .decode_frame(&mut l8, &mut r8, None, None)
            .map_err(|e| format!("decode frame {frame}: {e:?}"))?;
        let h8 = fnv_i8(2_166_136_261, &l8, &r8);
        all8 = fnv_bytes(all8, &h8.to_le_bytes());
    }

    let h = album.header();
    let src = album_path.replace('\\', "/");
    let body = format!(
        "// GENERATED by crates/uli-lite/examples/gen_album_pin.rs from the bit-exact Rust decoder — do not edit.\n\
         //\n\
         // Corpus: {src} ({blob_len} B)\n\
         //   {frames} frames, {samples} samples ({seconds:.2} s), {tracks} track(s), {rate} Hz\n\
         //\n\
         // EXPECTED_INT8 is FNV-1a 32 over the little-endian per-frame int8 hashes,\n\
         // in frame order, over frames 0..{last_frame} (frame 0 is the preroll).\n\
         // It is the fold examples/uli_bench performs.\n\
         \n\
         pub const N_FRAMES: u32 = {frames};\n\
         pub const EXPECTED_INT8: u32 = 0x{all8:08x};\n",
        src = src,
        blob_len = blob.len(),
        frames = h.n_frames,
        samples = h.n_samples,
        seconds = h.n_samples as f64 / h.sample_rate as f64,
        tracks = h.n_tracks,
        rate = h.sample_rate,
        last_frame = h.n_frames.saturating_sub(1),
        all8 = all8,
    );

    let mut out =
        BufWriter::new(File::create(&out_path).map_err(|e| format!("create {out_path}: {e}"))?);
    out.write_all(body.as_bytes())
        .map_err(|e| format!("write {out_path}: {e}"))?;
    out.flush().map_err(|e| format!("flush {out_path}: {e}"))?;

    println!(
        "album pin: {} frames, {} samples, int8={:08x} -> {}",
        h.n_frames, h.n_samples, all8, out_path
    );
    Ok(())
}
