//! Split-ladder item 5, PR 3 — the two Rice mechanisms, side by side, over
//! **real libFLAC partitions**.
//!
//! The unit tests in [`flac_lite::rice_hybrid`] drive hand-built windows
//! through a spec-order oracle, because the legs they exercise (a 400-bit unary
//! run, an order-30 remainder, a truncated codeword ending mid-byte) are legs no
//! caller in the crate reaches yet. This file is the other half of PR 3's
//! witness: the partitions the corpus actually contains, walked by both
//! mechanisms at once. PR 3 did **not** make the flip it was planned to make; PR 4
//! took the on-target cycle reading that flip was gated on (2026-11-06: the
//! calibration instrument under `mgba-test-runner`, both clips, two runs per arm),
//! and the reading came back **slower** — +9.71% FIXED / +2.64% LPC mean per frame,
//! +42.6 / +42.7 cycles per decoded sample, 314/314 frames slower, 0 inside the
//! ~9–13 cyc/frame layout-noise band. So the default is decided by measurement now
//! rather than deferred, and the second test here is what keeps that decision from
//! drifting in either direction.
//!
//! **Four independent walks have to agree for a case to pass**, which is what
//! makes the comparison worth having:
//!
//! 1. a **structure walk** reads the residual header and every partition header
//!    with the widths `residual::decode_residual` documents, skips each body by
//!    counting its bits one at a time (unary run, then `order` remainder bits —
//!    RFC 9639 §9.2.5's prose, values ignored because this walk only wants
//!    widths), and records the bit position each partition's *parameter field*
//!    starts at;
//! 2. the **incumbent** (`TableCountKernel`, the production default) decodes
//!    each partition from that recorded position;
//! 3. this PR's **twin** (`rice_hybrid::HybridRiceKernel`) decodes the same
//!    partition from the same recorded position;
//! 4. and the table's own `exit_bits`, generated by an independent `Bits` walk
//!    next to libFLAC's encoder, is where all three must end up.
//!
//! After every partition the two mechanisms' bit positions are compared against
//! *each other* **and** against where the structure walk said the next
//! partition's parameter field begins. A kernel that consumed one bit too many
//! or too few is convicted at the partition where it happened, not at the end of
//! a block of wrong samples — and a structure walk that had mis-read the
//! partition layout would land somewhere other than `exit_bits`.
//!
//! Two vectors additionally pin the **sample values to the reference decoder**:
//! for a FIXED subframe the residual *is* the forward difference of the decoded
//! block (Table 20 read the way libFLAC reads it: the k-th difference of the
//! output equals the residual), so the expected residuals follow from
//! `pcm_samples` — the output of `flac -d` — without consulting either
//! mechanism. The LPC vectors cannot be anchored that way (their coefficients
//! are not in the table) and do not need to be: `subframe_body_layout.rs`
//! already proves the *default* path's samples bit-exactly against `flac -d`, so
//! "the twin equals the default here" transfers that proof to the twin.
//!
//! What this file deliberately does **not** do:
//!
//! * It does not decode a whole frame, subframe, or stream with the twin. That
//!   would mean threading a kernel choice through `decode_residual` /
//!   `decode_subframe` / `decode_frame`, and PR 3's rule is that the default
//!   stays put until there is an on-target cycle reading. Nothing above the seam
//!   names a kernel.
//! * It does not flip the default, and since PR 4 nothing should: the reading that
//!   would have decided it says *stay*. `residual::decode_rice_partition` — the one
//!   line that names it — is unchanged, and `subframe_body_layout.rs` /
//!   `frame_run_layout.rs` keep witnessing the production path.
//!   [`the_default_still_names_the_incumbent`] pins that in the cheapest way
//!   available, so any future flip stays an attributable change and not a drift.
//! * It does not claim the twin is faster, or that either mechanism is
//!   real-time on a GBA. It claims equivalence, on the corpus, at the partition
//!   boundary — which is the boundary PR 4's cycle reading judged, and judged
//!   against the incumbent.

