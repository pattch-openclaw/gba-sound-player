//! The analysis side: window, aliasing fold, orthonormal DCT-IV.
//!
//! The shape is what the format needs. A hop of `M = 512` inside a `2M` window, folded
//! into a length-`M` real sequence and transformed by a 256-point complex FFT — the
//! standard fast route to a length-`M` DCT-IV, which is what an MDCT of this hop reduces
//! to once the time-domain aliasing is folded in. Coefficients at or beyond `NCODED` are
//! forced to zero **here**, because the format forbids energy there and a blob carrying it
//! is counted as `hfnz` by the reader.
//!
//! Three decisions worth naming:
//!
//! - **No libm.** Every constant comes from [`crate::mdct_tables`], generated by
//!   `scripts/gen_uli_mdct_tables.py` (E-R5, rule R5c). A transform whose constants depend
//!   on which math library answered cannot promise reproducible output, and the arithmetic
//!   here is otherwise exact — `tests/mdct.rs` pins the coefficients bit for bit against a
//!   frozen golden.
//! - **No in-place global scratch.** `z`, `v` and the FFT's reals and imaginaries are
//!   locals, so frames are independent and can be coded in parallel (R5a). File-static
//!   scratch would serialise every worker on the same buffer.
//! - **`f32` output.** The coefficients are rounded to `f32` here and every later stage —
//!   the M/S rotation, the quantiser — reads that `f32`. The rounding is therefore part of
//!   the signal path rather than an accident of storage, and widening it to `f64` later
//!   would change magnitudes at the noise floor, hence symbols, hence bytes.
//!
//! The window starts one hop *before* the frame's own output samples
//! (`t0 = (f - 1) * M`) and reads out of bounds at both ends: before the album is silence,
//! past its end is silence. That is what makes frame 0 a preroll — it has no previous
//! samples and its output is entirely overlap — and what makes the last frame's window run
//! off the end without a special case.

use uli_lite::format::{M, NCODED};

use crate::Error;
use crate::mdct_tables::{BREV, FFT_C, FFT_S, POST_C, POST_S, PRE_C, PRE_S, SC, win};
use crate::pcm::Samples;

/// The orthonormal DCT-IV of `v`, via a 256-point complex FFT.
///
/// `H = M / 2 = 256` is both the FFT size and the length of `v`, which is why the
/// pre-twiddle pairs `x[2k]` with `x[M-1-2k]`: that fold is the DCT-IV-into-FFT
/// identity, and the post-twiddle un-folds it into the even/odd output positions.
fn dct4_ortho(v: &[f64; M], y: &mut [f64; M]) {
    const H: usize = M / 2;
    let mut re = [0f64; H];
    let mut im = [0f64; H];

    for k in 0..H {
        let a = v[2 * k];
        let b = v[M - 1 - 2 * k];
        let j = BREV[k] as usize;
        re[j] = a * PRE_C[k] - b * PRE_S[k];
        im[j] = a * PRE_S[k] + b * PRE_C[k];
    }

    let mut len = 2usize;
    while len <= H {
        let half = len / 2;
        let step = H / len;
        let mut i = 0usize;
        while i < H {
            for k in 0..half {
                let c = FFT_C[k * step];
                let s = FFT_S[k * step];
                let br = re[i + k + half];
                let bi = im[i + k + half];
                let tr = br * c - bi * s;
                let ti = br * s + bi * c;
                re[i + k + half] = re[i + k] - tr;
                im[i + k + half] = im[i + k] - ti;
                re[i + k] += tr;
                im[i + k] += ti;
            }
            i += len;
        }
        len <<= 1;
    }

    for k in 0..H {
        let a = re[k];
        let b = im[k];
        y[2 * k] = SC * (a * POST_C[k] - b * POST_S[k]);
        y[M - 1 - 2 * k] = -SC * (a * POST_S[k] + b * POST_C[k]);
    }
}

/// One frame's MDCT coefficients in `f32`: `coef[0..M]` left, `coef[M..2M]` right.
///
/// The `f32` rounding is part of the signal path, not a storage choice: every later stage —
/// the M/S rotation and the quantiser — reads these values and decides magnitudes, classes
/// and signs from them. Coefficients at or beyond `NCODED` are zero because the format
/// forbids energy there, not as a compression saving.
pub fn mdct_frame(x: &Samples, f: usize, n_samples: usize, coef: &mut [f32; 2 * M]) {
    let h = M / 2;
    let t0 = f as i64 * M as i64 - M as i64;
    let mut z = [0f64; 2 * M];
    let mut v = [0f64; M];
    let mut y = [0f64; M];

    for ch in 0..2 {
        for (i, zi) in z.iter_mut().enumerate() {
            let t = t0 + i as i64;
            *zi = if t >= 0 && (t as usize) < n_samples {
                f64::from(x.at(t as usize, ch)) * win(i)
            } else {
                0.0
            };
        }
        // The 2M -> M time-domain aliasing fold. Naming the four quarter-strides
        // a = z[0..], b = z[256..], c = z[512..], d = z[768..], the fold is
        //   v[i] = -c[255-i] - d[i]      v[256+i] = a[i] - b[255-i]
        // — the negation and reversal are what turn the MDCT's four overlapping window
        // quadrants into a single DCT-IV. The strides are spelled out rather than sliced so
        // the offsets stay legible, and the array is split at `h` so the two halves borrow
        // independently.
        let (v_lo, v_hi) = v.split_at_mut(h);
        for i in 0..h {
            v_lo[i] = -z[M + (h - 1 - i)] - z[3 * h + i];
            v_hi[i] = z[i] - z[h + (h - 1 - i)];
        }
        dct4_ortho(&v, &mut y);
        for (k, out) in coef[ch * M..ch * M + M].iter_mut().enumerate() {
            *out = if k < NCODED { y[k] as f32 } else { 0.0 };
        }
    }
}

/// Read the album once, whole. The encoder is host-side and a 43-minute album is ~130 MB
/// of `f32`; the analysis window straddles hops in both directions, so a streaming reader
/// would have to buffer as much as it saves.
pub fn load(path: &std::path::Path, n_samples: usize) -> Result<Samples, Error> {
    Samples::open(path, n_samples)
}
