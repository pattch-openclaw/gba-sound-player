//! The analysis side: window, aliasing fold, orthonormal DCT-IV.
//!
//! A port of `mdct_frame` / `dct4_ortho` / `mdct_init` from
//! `gba-audio/encoder/enc_core.c`, line for line where the arithmetic is involved.
//! The shape is the one the format needs: a hop of `M = 512` over a `2M` window,
//! folded into a length-`M` real sequence and transformed by a 256-point complex
//! FFT, with the coefficients above `NCODED` forced to zero **here** — that is the
//! format's rule, and an encoder that leaves them nonzero produces a blob the
//! reader counts as `hfnz` and the decoder warns about.
//!
//! Two things are deliberately not copied from the reference:
//!
//! - **No libm.** Every constant comes from [`crate::mdct_tables`], which is
//!   generated by `scripts/gen_uli_mdct_tables.py` (E-R5, rule R5c). The
//!   arithmetic is otherwise identical, and `tests/mdct.rs` checks the
//!   coefficients against the reference's own `float` output frame by frame.
//! - **No in-place global scratch.** The reference parks `z`/`v`/`X` in a file
//!   static and mutates them per call; here they are locals, so frames are
//!   independent and the encoder can code them in parallel (R5a).
//!
//! The window starts one hop *before* the frame's own output samples
//! (`t0 = (f - 1) * M`) and reads out of bounds at both ends: before zero is
//! silent, past the end is silent, and the `t >= 0 && t < n` test is what the
//! reference's preroll frame relies on.

use uli_lite::format::{M, NCODED};

use crate::Error;
use crate::mdct_tables::{BREV, FFT_C, FFT_S, POST_C, POST_S, PRE_C, PRE_S, SC, win};
use crate::pcm::Samples;

/// The orthonormal DCT-IV of `v`, by the 256-point complex FFT the reference uses.
///
/// `H = M / 2 = 256` is both the FFT size and the length of `v`, which is why the
/// pre-twiddle pairs `x[2k]` with `x[M-1-2k]`: that fold is the DCT-IV-into-FFT
/// identity, and the post-twiddle un-folds it into the even/odd output positions.
fn dct4_ortho(v: &[f64; M], y: &mut [f64; M]) {
    const H: usize = M / 2;
    let mut re = [0f64; H];
    let mut im = [0f64; H];

    for k in 0..H {
        let a = v[2 * k];
        let b = v[M - 1 - 2 * k];
        let j = BREV[k] as usize;
        re[j] = a * PRE_C[k] - b * PRE_S[k];
        im[j] = a * PRE_S[k] + b * PRE_C[k];
    }

    let mut len = 2usize;
    while len <= H {
        let half = len / 2;
        let step = H / len;
        let mut i = 0usize;
        while i < H {
            for k in 0..half {
                let c = FFT_C[k * step];
                let s = FFT_S[k * step];
                let br = re[i + k + half];
                let bi = im[i + k + half];
                let tr = br * c - bi * s;
                let ti = br * s + bi * c;
                re[i + k + half] = re[i + k] - tr;
                im[i + k + half] = im[i + k] - ti;
                re[i + k] += tr;
                im[i + k] += ti;
            }
            i += len;
        }
        len <<= 1;
    }

    for k in 0..H {
        let a = re[k];
        let b = im[k];
        y[2 * k] = SC * (a * POST_C[k] - b * POST_S[k]);
        y[M - 1 - 2 * k] = -SC * (a * POST_S[k] + b * POST_C[k]);
    }
}

/// One channel's MDCT coefficients for frame `f`, in the reference's `float`
/// precision: `coef[0..M]` left, `coef[M..2M]` right.
///
/// The `f32` cast is not a convenience. The reference stores the transform into a
/// `float` array and every later stage — the M/S rotation and the quantiser —
/// reads that `float`, so the rounding to 24-bit significands is part of the
/// signal path S7 has to reproduce. Coefficients at or beyond `NCODED` are zero,
/// which is the format's rule rather than a compression choice.
pub fn mdct_frame(x: &Samples, f: usize, n_samples: usize, coef: &mut [f32; 2 * M]) {
    let h = M / 2;
    let t0 = f as i64 * M as i64 - M as i64;
    let mut z = [0f64; 2 * M];
    let mut v = [0f64; M];
    let mut y = [0f64; M];

    for ch in 0..2 {
        for (i, zi) in z.iter_mut().enumerate() {
            let t = t0 + i as i64;
            *zi = if t >= 0 && (t as usize) < n_samples {
                f64::from(x.at(t as usize, ch)) * win(i)
            } else {
                0.0
            };
        }
        // The 2M -> M aliasing fold. The reference names the four quarter-strides
        // a = z[0..], b = z[256..], c = z[512..], d = z[768..] and writes
        //   v[i] = -c[255-i] - d[i];   v[256+i] = a[i] - b[255-i]
        // which is what the DCT-IV-into-FFT derivation wants; the strides are
        // spelled out here rather than through slices so the offsets are legible.
        // Split at `h` so the two halves borrow independently; the reference writes
        // `v[i]` and `v[h + i]` in one loop, which is the same thing.
        let (v_lo, v_hi) = v.split_at_mut(h);
        for i in 0..h {
            v_lo[i] = -z[M + (h - 1 - i)] - z[3 * h + i];
            v_hi[i] = z[i] - z[h + (h - 1 - i)];
        }
        dct4_ortho(&v, &mut y);
        for (k, out) in coef[ch * M..ch * M + M].iter_mut().enumerate() {
            *out = if k < NCODED { y[k] as f32 } else { 0.0 };
        }
    }
}

/// Read the album once. The encoder is host-side and a 43-minute album is
/// ~130 MB of `f32`, which is what the reference itself `mmap`s.
pub fn load(path: &std::path::Path, n_samples: usize) -> Result<Samples, Error> {
    Samples::open(path, n_samples)
}
