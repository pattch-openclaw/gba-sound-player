//! Split-ladder item 6 PR **6a-3** — the Rice seam driven from **outside**
//! `flac-lite`, over the same committed corpus the core's own differential uses.
//!
//! Every differential the tree had before this PR lived inside the crate it
//! tested: `crates/flac-lite/tests/` is a separate crate, but it is the *core's*
//! tests directory, and the kernels it names
//! ([`flac_lite::residual::TableCountKernel`] and
//! [`flac_lite::rice_hybrid::HybridRiceKernel`]) are declared inside `src/`. So
//! the claim "the seam is implementable from outside the crate" — the claim
//! 6a-4's ARM-mode kernel rests on, with an FFI and an ABI stacked on top of it —
//! had no execution behind it. 6a-2's record says so in as many words: the E-series
//! sample probes each brought their *own* `parse_partition` and their own
//! `decode_rice_partition`, "neither calls the core's `rice_quotient`... that is
//! 6a-3's witness, and it is why 6a-3 exists."
//!
//! This file is that witness. The kernel on the second leg is
//! [`flac_lite_gba::rice_twin::TwinKernel`], declared in a different crate, with
//! its own `impl` block, reached through nothing but the core's public surface.
//!
//! # The fourth leg is the one 6a-4 needs
//!
//! Leg 4, [`SpecOrderKernel`], is not another optimization of the codeword loop.
//! It is a deliberately naive one — one `read_bits(1)` per unary bit, no window,
//! no table, no `rice_quotient`, and no access to anything inside `residual` —
//! written from [`RiceKernel`]'s stated contract and nothing else. Its purpose is
//! to test that the boundary the trait documents is *satisfiable by someone who
//! cannot see the core's loop*, which is the exact position 6a-4's ARM-mode kernel
//! will occupy across an FFI and a state-struct ABI, and which no earlier rung of
//! this ladder ever tested. It is also the reason this PR touches the core's
//! surface: the folded value's sign map is the one leg of that contract an
//! out-of-crate kernel cannot safely re-derive, and the first commit of this PR
//! makes [`flac_lite::residual::rice_unmap`] visible for exactly that call. That
//! function's docs carry what was considered and left private.
//!
//! # What has to agree, and why the agreement is not circular
//!
//! Five legs: four walks over the same bits, three of those walks being distinct
//! decode mechanisms, plus one committed oracle:
//!
//! 1. a **width walk** (this file) reads the residual header and each partition
//!    header at the widths §9.2.7 states, then skips every body one bit at a
//!    time per §9.2.5's prose — unary zeros until the terminating one, then
//!    `order` remainder bits — recording only widths. No window, no table, no
//!    word load, no kernel;
//! 2. the core's **incumbent**, instantiated here from outside:
//!    `decode_rice_partition_with::<TableCountKernel>`;
//! 3. this crate's **arm**, [`TwinKernel`] — the core's hybrid twin, carried
//!    through the seam by an impl written in another crate;
//! 4. this file's own **spec-order** kernel, [`SpecOrderKernel`], described below;
//! 5. the table's own **`exit_bits`**, generated by an independent `Bits` walk
//!    beside libFLAC's encoder (`scripts/gen_frame_vectors.sh`).
//!
//! Legs 2, 3 and 4 are then compared to *each other*, to leg 1's next-partition
//! positions, and to leg 5's endpoint. Three mechanisms all wrong in the same way
//! would agree with each other and still be convicted by the walk; a walk that
//! mis-read the layout would fail to land on `exit_bits`; and a table that had
//! drifted would be caught by the value anchor below.
//!
//! # The value anchor, so this is not only a self-consistency check
//!
//! For a FIXED subframe with predictor order ≤ 2 the residual *is* the forward
//! difference of the decoded block, so the expected sample values follow from the
//! table's `pcm_samples` — the output of `flac -d` — without consulting any of the
//! three mechanisms. That is what stops legs 2, 3 and 4 from being a tautology:
//! agreement among three kernels proves they compute the same function, not the
//! right one. The order-≥3 FIXED and the LPC vectors cannot be anchored that way
//! (their coefficients and differences are not in the table), and they do not need
//! to be: `subframe_body_layout.rs` in the core already proves the *default* path's
//! samples bit-exactly against `flac -d`, so "the arm equals the default here"
//! transfers that proof to the arm.
//!
//! # Why this file re-derives the walk instead of importing it
//!
//! Because importing is the thing that would make the witness test nothing about
//! the surface. If leg 1 came from the core's test helper, this file would prove
//! that the core's test still works; re-derived here, it proves the public
//! surface is *sufficient* to state the whole question from outside — which is
//! the other half of what 6a-3 exists to find out. It is duplication on purpose,
//! and it is the same argument the core's own differential makes about its two
//! mechanisms.
//!
//! # What this file does not do
//!
//! * It does not decode a whole frame, subframe or stream through the arm.
//!   Nothing above the seam threads a kernel choice:
//!   `residual::decode_rice_partition` still names `TableCountKernel` on one
//!   line, by item 5 PR 4's measurement. That rewiring is 6a-5's, taken with the
//!   cycle reading that decides it.
//! * Two guards it contains are not witnessed by the corpus, and that was
//!   measured rather than assumed. No committed sample folds to `u32::MAX`, so
//!   deleting either §9.2.7.3 rejection — this file's or the core twin's — leaves
//!   the suite green. The *map* is pinned at its extremes in the core
//!   (`rice_unmap(0xFFFF_FFFF) == i32::MIN`, in `residual.rs`'s own tests); what
//!   nothing here reaches is a kernel *rejecting* that pre-image. The other blind
//!   spot is the arm's forwarding target: pointing it at `TableCountKernel` is
//!   behaviour-neutral and the differential stays green — which is why
//!   `naming_a_kernel_from_outside_has_not_wired_one_in` puts a source pin on it
//!   instead of trusting the corpus. Both are mutation arms in the 6a-3 record.
//! * It claims nothing about cycles. The arm's number is item 5 PR 4's, taken in
//!   a different image; this item's rule is that cycle figures are comparable
//!   only within one image and across records only as absolute paired marginals.
//! * It is not the codegen witness. Whether an out-of-crate implementor
//!   re-triggers the +2,984 B item 5 PR 3 measured is a section-table question,
//!   and the record in `FLAC.md` answers it.
//! * Its “carried arm” leg is not wholly disjoint from the incumbent. `TwinKernel`
//!   forwards to `HybridRiceKernel`, and `HybridRiceKernel::decode_partition`
//!   itself falls back to `TableCountKernel::decode_partition` for `order >= 32`
//!   (`rice_hybrid.rs`). So on that branch the arm *is* the incumbent, one call
//!   deep. It never fires in the corpus (parameters are `<= 30`, and `30` is the
//!   5-bit coding method's ceiling), so the differential is not measuring the
//!   incumbent against itself; but the anti-tautology source pin below reads
//!   `rice_twin.rs` only, so it would not see a fallback hidden a level deeper. This
//!   is the same class of blind spot M5 names, recorded so 6a-4 knows the arm's
//!   `order >= 32` path is the incumbent's, not a second implementation’s.
//! * It does not reach any GBA-specific behavior: this suite runs on the host
//!   triple, like every other test in this repository.

use flac_lite::Error;
use flac_lite::bits::BitReader;
use flac_lite::frame::{FrameHeader, StreamDefaults};
use flac_lite::residual::{
    PartitionHeader, RiceKernel, TableCountKernel, decode_rice_partition_with,
};
use flac_lite::subframe::{PredictorState, SubframeType};
use flac_lite_gba::rice_twin::TwinKernel;

// The same committed table the core's own body-layout and two-mechanism tests
// read — reached by path, not copied. Copying it would be the drift this repo
// already pays for once elsewhere; a path reference has the failure mode we want
// instead, which is that renaming or moving the core's fixture makes *this* file
// stop compiling rather than quietly narrow.
const VECTOR_TABLE: &str = include_str!("../../flac-lite/tests/subframe_body_vectors.txt");

struct Vector {
    label: String,
    frame: Vec<u8>,
    sample_rate_hz: u64,
    bits_per_sample: u64,
    blocksize: u64,
    kind: String,
    order: u64,
    wasted: u64,
    subframe_bits: u64,
    warm_up: Vec<i64>,
    exit_bits: u64,
    pcm: Vec<i64>,
}

fn bytes_of(text: &str) -> Vec<u8> {
    text.split_whitespace()
        .map(|b| {
            u8::from_str_radix(b, 16)
                .unwrap_or_else(|e| panic!("non-hex byte {b:?} in {VECTOR_TABLE}: {e}"))
        })
        .collect()
}

fn ints_of(text: &str) -> Vec<i64> {
    if text.trim().is_empty() {
        return Vec::new();
    }
    text.split_whitespace()
        .map(|v| {
            v.parse()
                .unwrap_or_else(|e| panic!("not an integer {v:?}: {e}"))
        })
        .collect()
}

fn load() -> Vec<Vector> {
    let mut out: Vec<Vector> = Vec::new();
    for line in VECTOR_TABLE.lines() {
        let line = line.trim();
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        let (key, value) = line.split_once(char::is_whitespace).unwrap_or((line, ""));
        let value = value.trim();
        if key == "body_vector" {
            out.push(Vector {
                label: value.to_string(),
                frame: Vec::new(),
                sample_rate_hz: 0,
                bits_per_sample: 0,
                blocksize: 0,
                kind: String::new(),
                order: 0,
                wasted: 0,
                subframe_bits: 0,
                warm_up: Vec::new(),
                exit_bits: 0,
                pcm: Vec::new(),
            });
            continue;
        }
        let v = out
            .last_mut()
            .unwrap_or_else(|| panic!("{key:?} outside a body_vector block"));
        let number = || {
            value
                .strip_prefix("0x")
                .and_then(|h| u64::from_str_radix(h, 16).ok())
                .or_else(|| {
                    value
                        .parse::<i64>()
                        .ok()
                        .and_then(|x| u64::try_from(x).ok())
                })
                .unwrap_or_else(|| panic!("{key:?} is not a number: {value:?}"))
        };
        match key {
            "frame_hex" => v.frame = bytes_of(value),
            "stream_samplerate_hz" => v.sample_rate_hz = number(),
            "stream_bits_per_sample" => v.bits_per_sample = number(),
            "blocksize" => v.blocksize = number(),
            "subframe_kind" => v.kind = value.to_string(),
            "subframe_order" => v.order = number(),
            "subframe_wasted" => v.wasted = number(),
            "subframe_bits" => v.subframe_bits = number(),
            "warm_up_stream_order" => v.warm_up = ints_of(value),
            "exit_bits" => v.exit_bits = number(),
            "pcm_samples" => v.pcm = ints_of(value),
            _ => {}
        }
    }
    assert!(!out.is_empty(), "the corpus table read as empty");
    out
}

/// Advance by `bits`: `read_bits` serves at most 32 at a time, so a seek is a loop.
fn skip(reader: &mut BitReader<'_>, mut bits: usize) {
    while bits >= 32 {
        reader.read_bits(32).expect("seek a word");
        bits -= 32;
    }
    if bits > 0 {
        reader.read_bits(bits as u32).expect("seek the tail");
    }
}

/// Stop a reader on the first bit of the residual, using the same public calls
/// `subframe::decode_subframe` makes, in the same order. Deliberately not a
/// second formula for the subframe header's widths: it is the implementation's
/// own sequence, so the offset it yields cannot drift from the production one.
fn residual_start(v: &Vector) -> usize {
    let defaults = StreamDefaults {
        sample_rate_hz: v.sample_rate_hz as u32,
        bits_per_sample: v.bits_per_sample as u8,
    };
    let mut reader = BitReader::new(&v.frame);
    let header = FrameHeader::parse(&mut reader, &defaults)
        .unwrap_or_else(|e| panic!("{}: frame header: {e:?}", v.label));
    assert_eq!(
        header.blocksize, v.blocksize as usize,
        "{}: blocksize",
        v.label
    );

    let kind = SubframeType::parse(&mut reader)
        .unwrap_or_else(|e| panic!("{}: subframe type: {e:?}", v.label));
    let expect = match v.kind.as_str() {
        "fixed" => SubframeType::Fixed(v.order as u8),
        "lpc" => SubframeType::Lpc {
            order: v.order as u8,
        },
        other => panic!(
            "{}: {other} carries no residual to drive a kernel with",
            v.label
        ),
    };
    assert_eq!(kind, expect, "{}: subframe kind", v.label);
    let order = kind.order();

    let wasted = reader
        .read_wasted_bits()
        .unwrap_or_else(|e| panic!("{}: wasted run: {e:?}", v.label));
    assert_eq!(u64::from(wasted), v.wasted, "{}: wasted bits", v.label);
    let sub_bits = u32::from(header.bits_per_sample)
        .checked_sub(u32::from(wasted))
        .expect("subframe width after wasted bits");
    assert_eq!(
        u64::from(sub_bits),
        v.subframe_bits,
        "{}: subframe bits",
        v.label
    );

    let mut state = PredictorState::new();
    state
        .fill(&mut reader, order, sub_bits as u8, 0)
        .unwrap_or_else(|e| panic!("{}: warm-up: {e:?}", v.label));
    assert_eq!(state.len, order, "{}: warm-up count", v.label);
    for (i, got) in state.warm_up[..order].iter().rev().enumerate() {
        assert_eq!(
            i64::from(*got),
            v.warm_up[i],
            "{}: warm-up sample {i}",
            v.label
        );
    }

    if let SubframeType::Lpc { order } = kind {
        let precision_minus_one = reader
            .read_bits(4)
            .unwrap_or_else(|e| panic!("{}: LPC precision: {e:?}", v.label));
        assert_ne!(
            precision_minus_one, 0b1111,
            "{}: reserved LPC precision",
            v.label
        );
        let precision = precision_minus_one + 1;
        let shift = reader
            .read_signed(5)
            .unwrap_or_else(|e| panic!("{}: LPC shift: {e:?}", v.label));
        assert!(shift >= 0, "{}: negative LPC shift", v.label);
        for c in 0..order {
            reader
                .read_signed(precision)
                .unwrap_or_else(|e| panic!("{}: LPC coefficient {c}: {e:?}", v.label));
        }
    }
    reader.bit_position()
}

/// One partition as the width walk found it.
struct Partition {
    /// Where the parameter field begins — used to chain the partitions.
    param_at: usize,
    /// Where a kernel's reader has to start.
    body_at: usize,
    header: PartitionHeader,
}

/// Leg 1: the residual header, then every partition header and body width,
/// counted one bit at a time. Values are ignored; widths are the whole product.
fn residual_structure(v: &Vector, at: usize) -> (Vec<Partition>, usize, u32) {
    let mut reader = BitReader::new(&v.frame);
    skip(&mut reader, at);

    let method = reader.read_bits(2).expect("coding method");
    assert!(
        method <= 0b01,
        "{}: coding method {method:#04b} is reserved",
        v.label
    );
    let param_bits: u32 = if method == 0b00 { 4 } else { 5 };
    let partition_order = reader.read_bits(4).expect("partition order") as usize;
    let blocksize = v.blocksize as usize;
    assert_eq!(
        blocksize & ((1 << partition_order) - 1),
        0,
        "{}: blocksize not divisible by the partition count",
        v.label
    );
    let per_partition = blocksize >> partition_order;
    assert!(
        per_partition > v.order as usize,
        "{}: a partition cannot hold fewer samples than the predictor order",
        v.label
    );

    let mut found = Vec::new();
    for p in 0..(1usize << partition_order) {
        let param_at = reader.bit_position();
        let field = reader.read_bits(param_bits).expect("partition parameter");
        let mut header = PartitionHeader {
            order: 0,
            is_escape: false,
            raw_bits: 0,
            sample_count: 0,
        };
        if field == (1u32 << param_bits) - 1 {
            header.is_escape = true;
            header.raw_bits = reader.read_bits(5).expect("escape raw width") as u8;
        } else {
            header.order = field as u8;
        }
        header.sample_count =
            u16::try_from(per_partition - if p == 0 { v.order as usize } else { 0 })
                .expect("partition sample count");
        let body_at = reader.bit_position();
        found.push(Partition {
            param_at,
            body_at,
            header,
        });

        for _ in 0..header.sample_count {
            if header.is_escape {
                if header.raw_bits > 0 {
                    reader
                        .read_bits(u32::from(header.raw_bits))
                        .unwrap_or_else(|e| panic!("{}: escaped sample: {e:?}", v.label));
                }
                continue;
            }
            loop {
                match reader.read_bits(1) {
                    Ok(0) => {}
                    Ok(1) => break,
                    Ok(other) => unreachable!("one read bit is {other}"),
                    Err(e) => panic!("{}: unary run ran off the frame: {e:?}", v.label),
                }
            }
            if header.order > 0 {
                reader
                    .read_bits(u32::from(header.order))
                    .unwrap_or_else(|e| panic!("{}: remainder: {e:?}", v.label));
            }
        }
    }
    (found, reader.bit_position(), param_bits)
}

/// Decode one partition with `K`, starting at bit `at`.
fn with_kernel<K: RiceKernel>(
    frame: &[u8],
    at: usize,
    header: &PartitionHeader,
) -> (Vec<i32>, usize, Option<Error>) {
    let mut reader = BitReader::new(frame);
    skip(&mut reader, at);
    let mut out = vec![0i32; usize::from(header.sample_count)];
    let err = decode_rice_partition_with::<K>(&mut reader, header, &mut out).err();
    (out, reader.bit_position(), err)
}

/// The fourth mechanism: the same loop, written here from [`RiceKernel`]'s
/// contract and §9.2.5's prose, with nothing from the core's implementation.
///
/// This is the leg that tests whether the trait's *documented* boundary is
/// satisfiable by an implementor that cannot see the core's code — the position
/// 6a-4's kernel occupies, one FFI further out. So it is deliberately the slowest
/// possible way to do the work: one `read_bits(1)` per unary bit. Speed is not
/// what it is for, and no cycle figure anywhere in this item is taken from it.
///
/// What it owes, straight off the trait, and where each item lands in the lines
/// below:
///
/// * the `p = 0` mask — a parameter of 0 means the remainder is empty, and
///   `read_bits(0)` is a caller bug, so the leg is spelled out rather than folded
///   into a shift;
/// * §9.2.7.3's two rejections, which the trait assigns to the kernel because the
///   kernel is what computes the folded value. The `order >= 32` arm comes first
///   because `u32::MAX >> order` is itself a shift-by-32 hazard, and because
///   `checked_shl` is not the same check — item 5 found that the hard way;
/// * running out of bits is `EndOfStream`, which is what `read_bits` already
///   returns — the trait's stated reason `KernelWindow` carries no status field;
/// * the sign map, which it does **not** re-derive: it calls
///   [`flac_lite::residual::rice_unmap`], and that call is why the first commit of
///   this PR exists. A fourth copy of a mapping this repository has already
///   corrected once (step 3a, 2026-09-10) is a fourth place the correction can be
///   wrong.
///
/// Two honest differences, recorded rather than smoothed over. **No corpus case in
/// this table reaches either** — every vector decodes cleanly — so both are untested
/// here, not passed, and both matter to 6a-4, whose kernel has to say which side of
/// each it lands on:
///
/// 1. *Cursor on an unterminated final codeword.* The incumbent restores the cursor
///    to that codeword's start (the atomicity of `BitReader::rice_quotient`) while
///    this leg leaves it wherever the failing read stopped. The trait permits both —
///    "on error only per-read atomicity holds".
/// 2. *Guard order on an out-of-range parameter.* This leg checks
///    `order >= 32 || quotient > (u32::MAX >> order)` **after** reading the
///    remainder, whereas the incumbent checks `order >= 32` (and the quotient bound)
///    **before** it — so for a malformed `order >= 32` the two can return different
///    error variants (this leg reads up to 32 remainder bits first, and for
///    `order > 32` `read_bits` fails `EndOfStream` before the guard is reached). On
///    conforming input `order <= 30`, so this never fires in the corpus. It is kept
///    this way on purpose: it is the literal §9.2.5 reading (unary, then remainder,
///    then the representability check), which is exactly the naive-from-prose
///    property this leg exists to demonstrate. A `SpecOrderKernel` that reordered its
///    guard to match the incumbent would be reading the incumbent's code, not the
///    spec.
struct SpecOrderKernel;

impl RiceKernel for SpecOrderKernel {
    fn decode_partition(
        reader: &mut BitReader<'_>,
        order: u32,
        out: &mut [i32],
    ) -> flac_lite::Result<()> {
        for sample in out.iter_mut() {
            // §9.2.5's prose made executable: zeros, then the terminating one.
            let mut quotient = 0u32;
            while reader.read_bits(1)? == 0 {
                quotient += 1;
            }
            let remainder = if order == 0 {
                0
            } else {
                reader.read_bits(order)?
            };
            if order >= 32 || quotient > (u32::MAX >> order) {
                return Err(Error::InvalidField);
            }
            let folded = (quotient << order) | remainder;
            if folded == u32::MAX {
                // The unique pre-image of `i32::MIN`, forbidden in a stream.
                return Err(Error::InvalidField);
            }
            *sample = flac_lite::residual::rice_unmap(folded);
        }
        Ok(())
    }
}

#[test]
fn the_seam_is_passable_from_outside_and_the_arm_decodes_the_corpus_identically() {
    let vectors = load();
    let coded: Vec<&Vector> = vectors
        .iter()
        .filter(|v| v.kind == "fixed" || v.kind == "lpc")
        .collect();
    assert!(
        coded.len() >= 2,
        "this witness needs coded residuals; the table offers {} (kinds: {:?})",
        coded.len(),
        vectors.iter().map(|v| v.kind.as_str()).collect::<Vec<_>>()
    );

    let mut rice_partitions = 0usize;
    let mut escapes = 0usize;
    let mut parameters: Vec<u8> = Vec::new();
    let mut samples = 0usize;

    for v in &coded {
        let what = format!("vector {}", v.label);
        let start = residual_start(v);
        let (partitions, walk_end, param_bits) = residual_structure(v, start);
        assert!(
            !partitions.is_empty(),
            "{what}: a coded residual must carry a partition"
        );
        // The residual header is six bits under either method, so leg 1 and the
        // subframe walk above have to meet at `start + 6`.
        assert_eq!(
            partitions[0].param_at,
            start + 6,
            "{what}: the first partition's parameter field must begin at {}, leg 1 found {}",
            start + 6,
            partitions[0].param_at
        );

        let mut cursor = start;
        let mut decoded: Vec<i32> = Vec::new();
        for (i, p) in partitions.iter().enumerate() {
            if i > 0 {
                assert_eq!(
                    p.param_at, cursor,
                    "{what}: partition {i}'s parameter field is at {}, but the previous body \
                     ended at {cursor}",
                    p.param_at
                );
            }
            assert_eq!(
                p.body_at,
                p.param_at + param_bits as usize + if p.header.is_escape { 5 } else { 0 },
                "{what}: partition {i}: its body begins after its {param_bits}-bit parameter field",
            );
            if p.header.is_escape {
                escapes += 1;
            } else {
                rice_partitions += 1;
                parameters.push(p.header.order);
            }

            let (incumbent, at_a, err_a) =
                with_kernel::<TableCountKernel>(&v.frame, p.body_at, &p.header);
            let (arm, at_b, err_b) = with_kernel::<TwinKernel>(&v.frame, p.body_at, &p.header);
            let (spec, at_c, err_c) =
                with_kernel::<SpecOrderKernel>(&v.frame, p.body_at, &p.header);

            assert_eq!(
                err_a, err_b,
                "{what}: partition {i} (parameter {}, {} samples): the incumbent and the \
                 out-of-crate arm disagree about whether this decodes",
                p.header.order, p.header.sample_count
            );
            assert_eq!(
                err_a, err_c,
                "{what}: partition {i}: the incumbent and the spec-order leg disagree about \
                 whether this decodes",
            );
            if let Some(e) = err_a {
                panic!("{what}: partition {i} failed in all three: {e:?}");
            }
            assert_eq!(
                incumbent, arm,
                "{what}: partition {i} (parameter {}, {} samples, at bit {}): the out-of-crate \
                 arm and the incumbent disagree about the samples",
                p.header.order, p.header.sample_count, p.body_at
            );
            assert_eq!(
                incumbent, spec,
                "{what}: partition {i}: the spec-order leg disagrees with the incumbent about \
                 the samples, so the trait's documented boundary is not satisfiable from \
                 outside as written",
            );
            assert_eq!(
                at_a, at_b,
                "{what}: partition {i}: the incumbent and the carried arm landed at {at_a} and \
                 {at_b} — one of them consumed the wrong number of bits",
            );
            assert_eq!(
                at_a, at_c,
                "{what}: partition {i}: the spec-order leg landed at {at_c}, the incumbent at \
                 {at_a} — one of them consumed the wrong number of bits",
            );
            if i + 1 < partitions.len() {
                assert_eq!(
                    at_a,
                    partitions[i + 1].param_at,
                    "{what}: partition {i} ended at {at_a}; leg 1 says the next parameter \
                     field is at {}",
                    partitions[i + 1].param_at
                );
            }
            cursor = at_a;
            decoded.extend_from_slice(&incumbent);
            samples += incumbent.len();
        }

        assert_eq!(
            walk_end, v.exit_bits as usize,
            "{what}: the width walk ended at {walk_end}; the table's own oracle walk says {}",
            v.exit_bits
        );
        assert_eq!(
            cursor, v.exit_bits as usize,
            "{what}: the mechanisms ended at {cursor}; the table says {}",
            v.exit_bits
        );

        // The value anchor, where the predictor makes the residuals derivable from
        // the reference PCM alone: a FIXED subframe's residual is its forward
        // difference at the wasted-stripped scale.
        if v.kind == "fixed" && v.order <= 2 {
            let scaled: Vec<i64> = v.pcm.iter().map(|x| *x >> v.wasted as i64).collect();
            let expect: Vec<i32> = match v.order {
                0 => scaled.iter().map(|&x| x as i32).collect(),
                1 => (1..scaled.len())
                    .map(|i| (scaled[i] - scaled[i - 1]) as i32)
                    .collect(),
                _ => (2..scaled.len())
                    .map(|i| (scaled[i] - 2 * scaled[i - 1] + scaled[i - 2]) as i32)
                    .collect(),
            };
            assert_eq!(
                decoded, expect,
                "{what}: the residuals all three mechanisms decoded are not the forward \
                 difference of the reference PCM — so the table, leg 1, or one of the three \
                 mechanisms is wrong"
            );
        }
    }

    assert!(
        rice_partitions >= 4,
        "the corpus yielded {rice_partitions} Rice partitions; expected at least 4 — regenerate \
         it with scripts/gen_frame_vectors.sh",
    );
    parameters.sort_unstable();
    parameters.dedup();
    assert!(
        parameters.len() >= 2,
        "the corpus exercised only Rice parameter(s) {parameters:?} — one parameter value would \
         make this differential far weaker than it reads",
    );
    assert!(
        samples >= 512,
        "the corpus yielded {samples} residual samples; expected hundreds at least",
    );
    eprintln!(
        "out-of-crate seam witness: {} vectors, {rice_partitions} Rice partitions + {escapes} \
         escaped, {samples} samples, parameters {parameters:?}",
        coded.len()
    );
}

/// The invariant this crate's arm must never quietly break, pinned from the
/// outside: the core's decode path still names its incumbent kernel, and names
/// nothing from here.
///
/// This is the same pin
/// `crates/flac-lite/tests/rice_two_mechanism_differential.rs` puts on the core,
/// read from a second vantage. It is deliberately a source-level check rather than
/// a behavioral one — the kernels reachable from the core's default path are
/// bit-identical by construction, so no
/// corpus reading can distinguish them, which is exactly why item 5 PR 4's flip
/// had to be a separate cycle reading rather than something arriving inside a green
/// run. Read from here it means something slightly different, and narrower: that
/// an overlay which *can* name a kernel has not wired one in.
///
/// The same test pins the other half of the same non-obligation, on this side of
/// the boundary: that the arm *carries* the core's twin rather than re-pointing at
/// the core's incumbent. That one has to be a source pin too, and for a sharper
/// reason than the first. Re-routing the arm to `TableCountKernel` is
/// behaviour-neutral — the five-leg differential stays green, which is not a
/// theory: it is one of this file's mutation arms, and green is exactly what a
/// tautology looks like from inside. A differential whose two sides are the same
/// mechanism measures nothing, and 6a-5's comparison would be that differential.
#[test]
fn naming_a_kernel_from_outside_has_not_wired_one_in() {
    let source = include_str!("../../flac-lite/src/residual.rs");
    let body = source
        .split_once("\nfn decode_rice_partition(")
        .expect("the production entry point must exist under that exact name")
        .1
        .split("\n}")
        .next()
        .expect("and have a body");
    assert!(
        body.contains("decode_rice_partition_with::<TableCountKernel>"),
        "the default names TableCountKernel by measurement (item 5 PR 4, +42.6/+42.7 \
         cycles per decoded sample for the alternative). Anything reading this from outside \
         the core needs that to be true, because 6a-5's number is only interpretable \
         against it."
    );
    assert!(
        !body.contains("HybridRiceKernel") && !body.contains("TwinKernel"),
        "no kernel carried by an overlay is the core's default; if this changes, the \
         cycle reading that owns the change has to be in the same diff"
    );

    // And on this crate's side of the boundary: the arm exists to be instantiated
    // by a witness, not by a path. Enumerating this crate's own `src/` is how
    // that gets said without a comment-sensitive grep: 6a-3 declares exactly one
    // module, and nothing outside that module's own file names the arm in code.
    let src_dir = concat!(env!("CARGO_MANIFEST_DIR"), "/src");
    let mut files: Vec<String> = std::fs::read_dir(src_dir)
        .unwrap_or_else(|e| panic!("cannot read {src_dir}: {e}"))
        .map(|e| {
            e.expect("a src entry")
                .file_name()
                .to_string_lossy()
                .into_owned()
        })
        .collect();
    files.sort();
    assert_eq!(
        files,
        vec!["lib.rs", "rice_twin.rs"],
        "6a-3 declares exactly one module; a second one here has to be in the same diff \
         as the decode path or the ROM that uses it"
    );
    for file in &files {
        let text = std::fs::read_to_string(format!("{src_dir}/{file}"))
            .unwrap_or_else(|e| panic!("read {file}: {e}"));
        let code_naming_the_arm = text
            .lines()
            .map(str::trim)
            // Doc comments may name the arm — they should. Code lines may not,
            // outside the file that declares it.
            .filter(|l| !(l.starts_with("//") || l.starts_with("///") || l.starts_with("//!")))
            .filter(|l| l.contains("TwinKernel"))
            .collect::<Vec<_>>();
        if file == "rice_twin.rs" {
            assert!(
                code_naming_the_arm.len() >= 2,
                "the arm's own file must declare the type and implement the trait"
            );
            let code_lines = text
                .lines()
                .map(str::trim)
                .filter(|l| !(l.starts_with("//") || l.starts_with("///") || l.starts_with("//!")))
                .collect::<Vec<_>>();
            assert!(
                code_lines.iter().any(|l| l.contains("HybridRiceKernel")),
                "the arm forwards to the core's twin. A foreign kernel that *vendored* \
                 the hybrid walk would be a second copy of a mapping this project has \
                 already paid a no-drift witness for once (examples/arm-kernels) — \
                 carried is the decision, and 6a-4 replaces this body with an asm \
                 entry, it does not quietly re-point it"
            );
            assert!(
                !code_lines.iter().any(|l| l.contains("TableCountKernel")),
                "the arm does not forward to the core's incumbent: that would leave the \
                 differential comparing a kernel with itself, and every cycle reading \
                 downstream of it comparing nothing"
            );
        } else {
            assert!(
                code_naming_the_arm.is_empty(),
                "{file} names the arm in code: {code_naming_the_arm:?} — an instrument arm \
                 that reaches a module tree has become a decode path by accident"
            );
        }
    }
}
